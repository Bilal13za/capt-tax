"""CAPT Taxation — content-pack importer.

Loads a content pack JSON file (docs/CONTENT_PACK_SCHEMA.md) into the SQLite
database. Idempotent per book: re-running load_pack with the same book
`source_file` replaces that book's imported content (delete-then-insert inside
a single transaction) without touching student-created data (origin='student',
notes, bookmarks, attempts, study plans).

Public API:
    load_pack(conn, pack_path, is_demo=False) -> int (book id)
    get_active_book(conn) -> sqlite3.Row | None
    is_demo_stuck(conn, real_pack_path) -> bool
    repair_reload_real_pack(db_path) -> None

Accuracy contract (from the pack schema, binding on this importer):
  - page numbers are stored exactly as the pack gives them — never invented;
  - statement/solution/definition text is stored verbatim;
  - questions get qtype from the pack ('question_type' or 'qtype'), else 'theory'.
"""

from __future__ import annotations

import json
import re
from datetime import datetime, timezone
from pathlib import Path

from core.db import rebuild_fts

EXPECTED_PACK_FORMAT = 1

# Origins assigned to rows generated by this importer when the pack does not
# carry an explicit origin.
_IMPORTED_ORIGIN = "imported"
_DEMO_ORIGIN = "sample"


def _utcnow() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def _slug(label: str) -> str:
    slug = "".join(c.lower() if c.isalnum() else "_" for c in label.strip())
    return re.sub(r"_+", "_", slug).strip("_") or "topic"


def get_active_book(conn):
    """Return the active book row (sqlite3.Row) or None.

    The active book is settings.active_book_id when set and valid; otherwise
    the most recently created book.
    """
    row = conn.execute(
        "SELECT value FROM settings WHERE key='active_book_id'"
    ).fetchone()
    book = None
    if row is not None:
        try:
            book = conn.execute(
                "SELECT * FROM books WHERE id=?", (int(row["value"]),)
            ).fetchone()
        except (ValueError, TypeError):
            book = None
    if book is None:
        book = conn.execute(
            "SELECT * FROM books ORDER BY id DESC LIMIT 1"
        ).fetchone()
    return book


def load_pack(conn, pack_path, is_demo=False) -> int:
    """Validate and import a content pack into the database.

    Args:
        conn: open sqlite3 connection (row_factory=Row).
        pack_path: path to the pack JSON file.
        is_demo: when True the book row is marked is_demo=1 and generated
            items carry origin='sample' instead of 'imported'.

    Returns the new book id. Idempotent: if a book with the same
    `source_file` already exists, its imported content is deleted and
    re-inserted in one transaction.
    """
    pack = json.loads(Path(pack_path).read_text(encoding="utf-8"))
    if pack.get("pack_format") != EXPECTED_PACK_FORMAT:
        raise ValueError(
            "Unsupported pack_format %r (expected %d)"
            % (pack.get("pack_format"), EXPECTED_PACK_FORMAT)
        )
    book = pack.get("book") or {}
    source_file = book.get("source_file", "")
    if not source_file:
        raise ValueError("Pack book.source_file is required for idempotent import")

    generated_origin = _DEMO_ORIGIN if is_demo else _IMPORTED_ORIGIN

    with conn:  # single transaction: delete old book content, insert new
        existing = conn.execute(
            "SELECT id FROM books WHERE source_file=?", (source_file,)
        ).fetchone()
        if existing is not None:
            _delete_book_content(conn, existing["id"])
        book_id = _insert_book(conn, book, is_demo)
        _insert_chapters(conn, book_id, pack.get("chapters") or [])
        _insert_pages_and_slides(conn, book_id, pack.get("pages") or [],
                                 generated_origin)
        _insert_definitions(conn, pack.get("definitions") or [],
                            generated_origin)
        _insert_questions(conn, book_id, pack.get("questions") or [])
        conn.execute(
            "INSERT OR REPLACE INTO settings(key, value) VALUES ('active_book_id', ?)",
            (str(book_id),),
        )
    rebuild_fts(conn)
    return book_id


def _delete_book_content(conn, book_id: int) -> None:
    """Delete one book and everything imported from it, preserving
    student-created data (origin='student', notes, bookmarks, attempts,
    study plans/sessions, import_corrections, settings, backups)."""
    chapter_ids = [
        r["id"]
        for r in conn.execute(
            "SELECT id FROM chapters WHERE book_id=?", (book_id,)
        ).fetchall()
    ]
    ph = ",".join("?" for _ in chapter_ids) or "NULL"

    # Imported flashcards for these chapters (and their SM-2 state).
    card_ids = [
        r["id"]
        for r in conn.execute(
            f"SELECT id FROM flashcards WHERE chapter_id IN ({ph})"
            f" AND origin IN ('imported','sample','generated')",
            chapter_ids,
        ).fetchall()
    ] if chapter_ids else []
    if card_ids:
        cph = ",".join("?" for _ in card_ids)
        conn.execute(f"DELETE FROM sr_reviews WHERE card_id IN ({cph})", card_ids)
        conn.execute(f"DELETE FROM flashcards WHERE id IN ({cph})", card_ids)

    # Imported questions and their variants. Student-authored questions
    # (origin='student') survive a re-import so learner work is never lost.
    conn.execute(
        "DELETE FROM question_variants WHERE question_id IN "
        "(SELECT id FROM questions WHERE book_id=? "
        "AND (origin IS NULL OR origin != 'student'))",
        (book_id,),
    )
    conn.execute(
        "DELETE FROM questions WHERE book_id=? "
        "AND (origin IS NULL OR origin != 'student')",
        (book_id,),
    )

    # Slides belong to pages of this book.
    conn.execute(
        "DELETE FROM slides WHERE page_n IN "
        "(SELECT n FROM pages WHERE book_id=?)",
        (book_id,),
    )
    conn.execute("DELETE FROM pages WHERE book_id=?", (book_id,))

    # Items / tax rules / topics imported with this book's chapters.
    if chapter_ids:
        conn.execute(
            f"DELETE FROM items WHERE chapter_id IN ({ph})"
            f" AND origin IN ('imported','sample','generated','ocr')",
            chapter_ids,
        )
        conn.execute(
            f"DELETE FROM tax_rules WHERE chapter_id IN ({ph})", chapter_ids
        )
        conn.execute(
            f"DELETE FROM topics WHERE chapter_id IN ({ph})", chapter_ids
        )
    conn.execute("DELETE FROM chapters WHERE book_id=?", (book_id,))
    conn.execute("DELETE FROM books WHERE id=?", (book_id,))


def _insert_book(conn, book: dict, is_demo: bool) -> int:
    cur = conn.execute(
        """INSERT INTO books(title, volume, edition, author, publisher,
                             source_file, page_count, tax_context_note,
                             solutions_note, is_demo, created_at)
           VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)""",
        (
            book.get("title", ""),
            book.get("volume", ""),
            book.get("edition", ""),
            book.get("author", ""),
            book.get("publisher", ""),
            book.get("source_file", ""),
            book.get("page_count"),
            book.get("tax_context_note", ""),
            book.get("solutions_note", ""),
            1 if is_demo else 0,
            _utcnow(),
        ),
    )
    return cur.lastrowid


def _insert_chapters(conn, book_id: int, chapters: list) -> None:
    for ch in chapters:
        ch_id = ch.get("id")
        if not ch_id:
            continue
        parts = ch.get("parts") or []
        conn.execute(
            """INSERT INTO chapters(id, book_id, number, title,
                                    page_start, page_end, parts_json)
               VALUES (?, ?, ?, ?, ?, ?, ?)""",
            (
                ch_id,
                book_id,
                ch.get("number"),
                ch.get("title", ""),
                ch.get("page_start"),
                ch.get("page_end"),
                json.dumps(parts, ensure_ascii=False),
            ),
        )
        # Chapter "parts" become topics (deterministic ids).
        for i, part in enumerate(parts):
            topic_id = f"{ch_id}::part::{i}"
            conn.execute(
                """INSERT OR IGNORE INTO topics(id, chapter_id, name,
                                                sort_order, objectives_json)
                   VALUES (?, ?, ?, ?, '[]')""",
                (topic_id, ch_id, str(part), i),
            )


def _topic_for_slide_label(conn, chapter_id: str, label: str):
    """Return (creating if needed) a topic id for a slide footer label.

    Matches an existing chapter topic by name first (case-insensitive);
    otherwise creates a deterministic '<chapter_id>::slide::<slug>' topic.
    Empty label -> None (link not determinable; never invented).
    """
    label = (label or "").strip()
    if not label:
        return None
    row = conn.execute(
        "SELECT id FROM topics WHERE chapter_id=? AND LOWER(name)=LOWER(?)",
        (chapter_id, label),
    ).fetchone()
    if row is not None:
        return row["id"]
    topic_id = f"{chapter_id}::slide::{_slug(label)}"
    conn.execute(
        """INSERT OR IGNORE INTO topics(id, chapter_id, name, sort_order,
                                        objectives_json, source_ref)
           VALUES (?, ?, ?, ?, '[]', '')""",
        (topic_id, chapter_id, label, 10_000),
    )
    return topic_id


def _insert_pages_and_slides(conn, book_id: int, pages: list,
                             generated_origin: str) -> None:
    for pg in pages:
        n = pg.get("n")
        if n is None:
            continue
        chapter_id = pg.get("chapter_id")
        slides = pg.get("slides") or []
        # text_merged: use the pack's page text when provided, else derive
        # from the slide texts (verbatim concatenation, not invention).
        text_merged = pg.get("text")
        if text_merged is None:
            text_merged = "\n\n".join(s.get("text", "") for s in slides)
        conn.execute(
            """INSERT INTO pages(n, book_id, chapter_id, has_slides, failed,
                                 text_merged)
               VALUES (?, ?, ?, ?, ?, ?)""",
            (
                n,
                book_id,
                chapter_id,
                1 if pg.get("has_slides") else 0,
                1 if pg.get("failed") else 0,
                text_merged,
            ),
        )
        for order, s in enumerate(slides):
            title = s.get("title", "") or ""
            body = s.get("text", "") or ""
            topic_label = s.get("topic", "") or ""
            topic_id = (
                _topic_for_slide_label(conn, chapter_id, topic_label)
                if chapter_id
                else None
            )
            conn.execute(
                """INSERT INTO slides(page_n, title, topic, text, sort_order)
                   VALUES (?, ?, ?, ?, ?)""",
                (n, title, topic_label, body, order),
            )
            # Each slide also becomes a note item so it is searchable and
            # usable by Learn/Flashcards, linked to chapter/topic where
            # determinable.
            conn.execute(
                """INSERT INTO items(kind, topic_id, chapter_id, title, body,
                                    page_start, page_end, source_ref, origin,
                                    status, extra_json)
                   VALUES ('note', ?, ?, ?, ?, ?, ?, '', ?, 'verified', '{}')""",
                (
                    topic_id,
                    chapter_id,
                    title,
                    body,
                    n,
                    n,
                    generated_origin,
                ),
            )


def _insert_definitions(conn, definitions: list, generated_origin: str) -> None:
    for d in definitions:
        page = d.get("page")
        conn.execute(
            """INSERT INTO items(kind, topic_id, chapter_id, title, body,
                                page_start, page_end, source_ref, origin,
                                status, extra_json)
               VALUES ('definition', NULL, ?, ?, ?, ?, ?, ?, ?, ?, ?)""",
            (
                d.get("chapter_id"),
                d.get("term", ""),
                d.get("definition", ""),
                page,
                page,
                d.get("section_ref", "") or "",
                d.get("origin", generated_origin) or generated_origin,
                d.get("status", "auto_detected_unverified"),
                json.dumps({"pack_id": d.get("id", "")}, ensure_ascii=False),
            ),
        )


def _insert_questions(conn, book_id: int, questions: list) -> None:
    for q in questions:
        qid = q.get("id")
        if not qid:
            continue
        qtype = q.get("question_type") or q.get("qtype") or "theory"
        conn.execute(
            """INSERT INTO questions(id, book_id, chapter_id, topic_id, number,
                                    section, statement, solution, has_solution,
                                    page_start, page_end, origin,
                                    verified_answer, answer_note, qtype,
                                    difficulty, marks, suggested_minutes,
                                    rubric_json, numeric_answer,
                                    numeric_tolerance, rounding,
                                    mcq_options_json, mcq_answer,
                                    alt_answers_json)
               VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?,
                       ?, ?, ?, ?, ?, ?, ?)""",
            (
                qid,
                book_id,
                q.get("chapter_id"),
                q.get("topic_id"),
                str(q.get("number", "")),
                q.get("section", "") or "",
                q.get("statement", "") or "",
                q.get("solution", "") or "",
                1 if q.get("has_solution") else 0,
                q.get("page_start"),
                q.get("page_end"),
                q.get("origin", "imported") or "imported",
                1 if q.get("verified_answer") else 0,
                q.get("answer_note", "") or "",
                qtype,
                q.get("difficulty"),
                q.get("marks"),
                q.get("suggested_minutes"),
                json.dumps(q.get("rubric") or [], ensure_ascii=False),
                q.get("numeric_answer"),
                q.get("numeric_tolerance"),
                q.get("rounding"),
                json.dumps(q.get("mcq_options") or [], ensure_ascii=False),
                q.get("mcq_answer"),
                json.dumps(q.get("alt_answers") or [], ensure_ascii=False),
            ),
        )


def is_demo_stuck(conn, real_pack_path) -> bool:
    """True when the DB holds only DEMO content but the real pack exists.

    This happens when a stale/demo ``app.db`` shipped with or survived an
    install (e.g. bundled by mistake, or left over from an earlier version).
    The app then shows the single demo chapter forever because the loader
    only imports a pack into an *empty* database.
    """
    try:
        total = conn.execute("SELECT COUNT(*) AS c FROM books").fetchone()["c"]
        if not total:
            return False
        demo = conn.execute(
            "SELECT COUNT(*) AS c FROM books WHERE is_demo=1").fetchone()["c"]
        return demo == total and Path(real_pack_path).is_file()
    except Exception:
        return False


def repair_reload_real_pack(db_path) -> None:
    """Delete the database files so the next open re-creates an empty DB.

    The app's normal startup path then loads the real pack via
    ``_initial_pack``. Only call this after :func:`is_demo_stuck` is True —
    the database holds nothing but demo content at that point.
    """
    for suffix in ("", "-wal", "-journal", "-shm"):
        p = Path(str(db_path) + suffix)
        try:
            if p.is_file():
                p.unlink()
        except OSError:
            pass
